import assert from 'node:assert/strict';
import test from 'node:test';
import { DiaryData } from '../apps/diary/diary-data.js';

function fixture(t, counts) {
    const oldWindow = globalThis.window;
    const oldTimeout = globalThis.setTimeout;
    const notifications = [];
    globalThis.window = { VirtualPhone: { notify: (...args) => notifications.push(args) } };
    globalThis.setTimeout = callback => { callback(); return 0; };
    t.after(() => { globalThis.window = oldWindow; globalThis.setTimeout = oldTimeout; });
    const data = Object.create(DiaryData.prototype);
    let index = 0;
    data.callAIToWriteDiary = async () => Array.from({ length: counts[index++] }, () => ({ content: 'diary' }));
    data.addEntry = entry => entry;
    data.setAutoLastFloor = () => {};
    data.getCurrentChatIdentity = () => 'chat';
    return { data, notifications };
}

test('three batches report their own saved counts and ranges, including the final batch', async t => {
    const { data, notifications } = fixture(t, [1, 2, 1]);
    const completed = [];
    const entries = await data.batchGenerateDiary(0, 300, 100, (current, total, status, batch) => {
        if (batch) completed.push({ current, total, ...batch });
    });
    assert.equal(entries.length, 4);
    assert.deepEqual(completed, [
        { current: 1, total: 3, count: 1, startIndex: 0, endIndex: 100 },
        { current: 2, total: 3, count: 2, startIndex: 100, endIndex: 200 },
        { current: 3, total: 3, count: 1, startIndex: 200, endIndex: 300 }
    ]);
    assert.equal(notifications.length, 0); // Manual notifications belong to the view.
});

test('automatic batching emits one notification per batch without an aggregate notification', async t => {
    const { data, notifications } = fixture(t, [1, 2, 1]);
    data._getContext = () => ({ chat: new Array(300) });
    data.getAutoLastFloor = () => -1;
    data.getAutoSettings = () => ({ batchMode: true, autoFloor: 100 });
    await data.autoGenerateDiary({ chatId: 'chat' });
    assert.equal(notifications.length, 3);
    assert.equal(notifications[2][1], '第 3/3 批完成，本批新增 1 篇（200-300 层）');
    assert.ok(!notifications.some(args => args[1].includes('新增 4 篇')));
});

test('empty final batch still has a completion report with zero entries', async t => {
    const { data, notifications } = fixture(t, [1, 0]);
    await data.batchGenerateDiary(0, 150, 100, null, true);
    assert.equal(notifications.length, 2);
    assert.equal(notifications[1][1], '第 2/2 批完成，本批新增 0 篇（100-150 层）');
});
